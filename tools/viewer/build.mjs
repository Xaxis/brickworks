// The viewer Claude shows beside a call, built into one page (MCP Apps):
// tools/viewer/card.html with card.js, lbm.js, scene.js and the parts of
// three.js they use, bundled and minified, written as api/_viewer_page.js,
// which the relay serves as ui://brickworks/model.html (api/_viewer.js).
//
//   node tools/viewer/build.mjs --deps=DIR            write api/_viewer_page.js
//   node tools/viewer/build.mjs --deps=DIR --check    fail if it is not what is committed
//
// DIR holds node_modules with exactly the versions below and nothing run
// from it but esbuild, kept apart from this checkout as downloaded code is:
//
//   mkdir -p DIR && npm install --prefix DIR --ignore-scripts --save-exact three@0.186.1 esbuild@0.28.2
//
// The page is self-contained, script and all: the one thing it fetches is
// each part's geometry, from where the app fetches it. The built page is
// committed, since the deploy (tools/deploy.sh) copies api/ and builds
// nothing; --check is how a change to the source is held to a build.
import { createRequire } from "node:module";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const PINNED = { three: "0.186.1", esbuild: "0.28.2" };
const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "..", "api", "_viewer_page.js");
const args = Object.fromEntries(process.argv.slice(2).map((a) => {
  const [k, ...rest] = a.replace(/^--/, "").split("=");
  return [k, rest.join("=") || true];
}));
const deps = String(args.deps || "");
if (!deps || !existsSync(join(deps, "node_modules"))) {
  console.error("build: --deps=DIR, a directory with node_modules (see the head of this file)");
  process.exit(2);
}
for (const [name, version] of Object.entries(PINNED)) {
  const found = JSON.parse(readFileSync(join(deps, "node_modules", name, "package.json"), "utf8")).version;
  if (found !== version) {
    console.error(`build: ${name} is ${found} in ${deps}, not ${version}`);
    process.exit(2);
  }
}
const esbuild = createRequire(join(deps, "package.json"))("esbuild");
const built = await esbuild.build({
  entryPoints: [join(here, "card.js")],
  bundle: true,
  minify: true,
  format: "iife",
  target: "es2020",
  legalComments: "none",
  write: false,
  nodePaths: [join(deps, "node_modules")],
  logLevel: "warning",
});
// Nothing in a script may close the element it is in.
const script = built.outputFiles[0].text.trim().replace(/<\/(script)/gi, "<\\/$1");
const page = readFileSync(join(here, "card.html"), "utf8");
if (!page.includes("/*SCRIPT*/")) throw new Error("card.html has no /*SCRIPT*/ for the script");
const html = page.replace("/*SCRIPT*/", () => script);
const text = "// Generated by tools/viewer/build.mjs from tools/viewer/ (card.html, card.js, lbm.js,\n"
  + `// scene.js) and three.js ${PINNED.three} (MIT, the three.js authors, threejs.org), with esbuild\n`
  + `// ${PINNED.esbuild}. Do not edit: change tools/viewer/ and build again.\n`
  + `export const VIEWER_HTML = ${JSON.stringify(html)};\n`;
const kb = (n) => `${Math.round(n / 1024)} KB`;
if (args.check) {
  const committed = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (committed !== text) {
    console.error(`build: api/_viewer_page.js is not the build of tools/viewer/ (${kb(committed.length)} committed, ${kb(text.length)} built)`);
    process.exit(1);
  }
  console.log(`build: api/_viewer_page.js is the build of tools/viewer/, ${kb(html.length)}`);
} else {
  writeFileSync(out, text);
  console.log(`build: wrote api/_viewer_page.js, the page ${kb(html.length)} (its script ${kb(script.length)})`);
}
