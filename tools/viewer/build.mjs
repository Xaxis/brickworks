// The model in 3D, built twice from one scene (view.js, scene.js, web/lbm.js
// and the parts of three.js they use), each bundled and minified:
//
//   the viewer Claude shows beside a call, one page (MCP Apps):
//     tools/viewer/card.html with card.js, written as api/_viewer_page.js,
//     which the relay serves as ui://brickworks/model.html (api/_viewer.js)
//   a model's page's 3D view: inline.js, a module written as
//     web/viewer3d.js, which web/model-page.js imports only when it is
//     asked for
//
//   node tools/viewer/build.mjs --deps=DIR            write both
//   node tools/viewer/build.mjs --deps=DIR --check    fail if either is not what is committed
//
// DIR holds node_modules with exactly the versions below and nothing run
// from it but esbuild, kept apart from this checkout as downloaded code is:
//
//   mkdir -p DIR && npm install --prefix DIR --ignore-scripts --save-exact three@0.186.1 esbuild@0.28.2
//
// The card's page is self-contained, script and all: the one thing it
// fetches is each part's geometry, from where the app fetches it. Both are
// committed, since the deploy (tools/deploy.sh) copies api/ and web/ and
// builds nothing; --check is how a change to the source is held to a build.
import { createRequire } from "node:module";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const PINNED = { three: "0.186.1", esbuild: "0.28.2" };
const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "..", "api", "_viewer_page.js");
const outInline = join(here, "..", "..", "web", "viewer3d.js");
const args = Object.fromEntries(process.argv.slice(2).map((a) => {
  const [k, ...rest] = a.replace(/^--/, "").split("=");
  return [k, rest.join("=") || true];
}));
const deps = String(args.deps || "");
if (!deps || !existsSync(join(deps, "node_modules"))) {
  console.error("build: --deps=DIR, a directory with node_modules (see the head of this file)");
  process.exit(2);
}
for (const [name, version] of Object.entries(PINNED)) {
  const found = JSON.parse(readFileSync(join(deps, "node_modules", name, "package.json"), "utf8")).version;
  if (found !== version) {
    console.error(`build: ${name} is ${found} in ${deps}, not ${version}`);
    process.exit(2);
  }
}
const esbuild = createRequire(join(deps, "package.json"))("esbuild");
const bundle = (entry, format) => esbuild.build({
  entryPoints: [join(here, entry)],
  bundle: true,
  minify: true,
  format,
  target: "es2020",
  legalComments: "none",
  write: false,
  nodePaths: [join(deps, "node_modules")],
  logLevel: "warning",
});
const built = await bundle("card.js", "iife");
const builtInline = await bundle("inline.js", "esm");
// Nothing in a script may close the element it is in.
const script = built.outputFiles[0].text.trim().replace(/<\/(script)/gi, "<\\/$1");
const page = readFileSync(join(here, "card.html"), "utf8");
if (!page.includes("/*SCRIPT*/")) throw new Error("card.html has no /*SCRIPT*/ for the script");
const html = page.replace("/*SCRIPT*/", () => script);
const text = "// Generated by tools/viewer/build.mjs from tools/viewer/ (card.html, card.js, scene.js),\n"
  + `// web/lbm.js and three.js ${PINNED.three} (MIT, the three.js authors, threejs.org), with esbuild\n`
  + `// ${PINNED.esbuild}. Do not edit: change tools/viewer/ and build again.\n`
  + `export const VIEWER_HTML = ${JSON.stringify(html)};\n`;
const inline = "// Generated by tools/viewer/build.mjs from tools/viewer/ (inline.js, view.js, scene.js),\n"
  + `// web/lbm.js, web/card.js and three.js ${PINNED.three} (MIT, the three.js authors, threejs.org), with\n`
  + `// esbuild ${PINNED.esbuild}. Do not edit: change tools/viewer/ and build again.\n`
  + builtInline.outputFiles[0].text.trim() + "\n";
const kb = (n) => `${Math.round(n / 1024)} KB`;
if (args.check) {
  let stale = 0;
  for (const [file, name, made] of [[out, "api/_viewer_page.js", text], [outInline, "web/viewer3d.js", inline]]) {
    const committed = existsSync(file) ? readFileSync(file, "utf8") : "";
    if (committed !== made) {
      console.error(`build: ${name} is not the build of tools/viewer/ (${kb(committed.length)} committed, ${kb(made.length)} built)`);
      stale += 1;
    } else console.log(`build: ${name} is the build of tools/viewer/, ${kb(made.length)}`);
  }
  if (stale) process.exit(1);
} else {
  writeFileSync(out, text);
  writeFileSync(outInline, inline);
  console.log(`build: wrote api/_viewer_page.js, the page ${kb(html.length)} (its script ${kb(script.length)}), `
    + `and web/viewer3d.js, ${kb(inline.length)}`);
}
